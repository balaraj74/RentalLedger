    latitude      numeric(9,6) CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    longitude     numeric(9,6) CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    UNIQUE (customer_id, address_id)
