-- 10. Enforce same-vendor ownership for package components and booking lines.
CREATE OR REPLACE FUNCTION enforce_package_item_vendor()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    package_vendor integer;
    item_vendor integer;
BEGIN
    SELECT vendor_id INTO package_vendor FROM packages WHERE package_id = NEW.package_id;
    SELECT vendor_id INTO item_vendor FROM items WHERE item_id = NEW.item_id;
    IF package_vendor IS NULL OR item_vendor IS NULL OR package_vendor <> item_vendor THEN
        RAISE EXCEPTION 'Package and component item must belong to the same vendor';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_package_item_vendor
BEFORE INSERT OR UPDATE OF package_id, item_id ON package_items
FOR EACH ROW EXECUTE FUNCTION enforce_package_item_vendor();

CREATE OR REPLACE FUNCTION enforce_booking_item_vendor()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    source_vendor integer;
BEGIN
    IF NEW.item_id IS NOT NULL THEN
        SELECT vendor_id INTO source_vendor FROM items WHERE item_id = NEW.item_id;
    ELSE
        SELECT vendor_id INTO source_vendor FROM packages WHERE package_id = NEW.package_id;
    END IF;
    IF source_vendor IS NULL OR source_vendor <> NEW.vendor_id THEN
        RAISE EXCEPTION 'Booking-line vendor must own the selected item or package';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_booking_item_vendor
BEFORE INSERT OR UPDATE OF vendor_id, item_id, package_id ON booking_items
FOR EACH ROW EXECUTE FUNCTION enforce_booking_item_vendor();

-- 11. Availability function for search/display. This is NOT, by itself, a reservation lock.
CREATE OR REPLACE FUNCTION available_stock_for_item(
    p_item_id integer,
    p_start_date date,
    p_end_date date
) RETURNS integer
LANGUAGE plpgsql STABLE AS $$
DECLARE
    stock_total integer;
    stock_allocated bigint;
BEGIN
    IF p_end_date < p_start_date THEN
        RAISE EXCEPTION 'End date must be on or after start date';
    END IF;

    SELECT total_stock INTO stock_total
    FROM items
    WHERE item_id = p_item_id AND is_active = true;

    IF stock_total IS NULL THEN
        RETURN 0;
    END IF;

    IF EXISTS (
        SELECT 1 FROM item_blackout_dates ib
        WHERE ib.item_id = p_item_id
          AND daterange(ib.start_date, ib.end_date, '[]') && daterange(p_start_date, p_end_date, '[]')
    ) THEN
        RETURN 0;
    END IF;

    SELECT COALESCE(SUM(a.quantity_allocated), 0) INTO stock_allocated
    FROM booking_item_allocations a
    WHERE a.item_id = p_item_id
      AND a.allocation_status IN ('reserved', 'held')
      AND (a.allocation_status = 'reserved' OR a.hold_expires_at > now())
      AND daterange(a.rental_start_date, a.rental_end_date, '[]') && daterange(p_start_date, p_end_date, '[]');

    RETURN GREATEST(stock_total - stock_allocated, 0);
END;
$$;

-- 12. Trigger-maintained booking line total. This is the pre-discount line total.
CREATE OR REPLACE FUNCTION recalculate_booking_total()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    target_booking_id integer;
BEGIN
    IF TG_OP = 'DELETE' THEN
        target_booking_id := OLD.booking_id;
        UPDATE bookings b SET total_amount = COALESCE((
            SELECT SUM(bi.quantity * bi.price_at_booking)
            FROM booking_items bi WHERE bi.booking_id = target_booking_id
        ), 0) WHERE b.booking_id = target_booking_id;
        RETURN OLD;
    END IF;

    target_booking_id := NEW.booking_id;
    UPDATE bookings b SET total_amount = COALESCE((
        SELECT SUM(bi.quantity * bi.price_at_booking)
        FROM booking_items bi WHERE bi.booking_id = target_booking_id
    ), 0) WHERE b.booking_id = target_booking_id;

    IF TG_OP = 'UPDATE' AND OLD.booking_id <> NEW.booking_id THEN
        UPDATE bookings b SET total_amount = COALESCE((
            SELECT SUM(bi.quantity * bi.price_at_booking)
            FROM booking_items bi WHERE bi.booking_id = OLD.booking_id
        ), 0) WHERE b.booking_id = OLD.booking_id;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_recalculate_booking_total
AFTER INSERT OR UPDATE OR DELETE ON booking_items
FOR EACH ROW EXECUTE FUNCTION recalculate_booking_total();

-- 13. Automatic booking status history. The API may set app.user_id for attribution.
CREATE OR REPLACE FUNCTION log_booking_status_change()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO booking_status_history (booking_id, old_status, new_status, changed_by)
        VALUES (NEW.booking_id, OLD.status, NEW.status,
                NULLIF(current_setting('app.user_id', true), '')::integer);
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_booking_status_history
AFTER UPDATE OF status ON bookings
FOR EACH ROW EXECUTE FUNCTION log_booking_status_change();

COMMIT;

-- IMPLEMENTATION CONTRACT: booking confirmation must run inside one transaction.
-- 1. Resolve a direct item line to {item_id: line quantity}; resolve a package line
--    by multiplying package_items.quantity by booking_items.quantity for each component.
-- 2. Lock all required items in ascending item_id order using SELECT ... FOR UPDATE.
-- 3. Calculate availability again while holding those locks. Reject if any component
--    is short or blacked out. Do not rely solely on available_stock_for_item(), because
--    a display-time SELECT is not a concurrency guarantee.
-- 4. Insert allocation rows (held with expiry or reserved after confirmation) for every
--    required component. Confirm the booking only if all allocation inserts succeed.
-- 5. On any failure, ROLLBACK the entire transaction. On cancellation, release the
--    affected allocations in the same transaction. Record returns by setting allocation
--    status to returned and returned_at; Version 1 models full allocation returns.
