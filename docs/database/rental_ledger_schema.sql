-- 5. Physical stock commitment: direct item rentals and package components both allocate here.
CREATE TABLE booking_item_allocations (
    allocation_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_item_id      integer NOT NULL REFERENCES booking_items(booking_item_id) ON DELETE RESTRICT,
    item_id              integer NOT NULL REFERENCES items(item_id) ON DELETE RESTRICT,
    quantity_allocated   integer NOT NULL CHECK (quantity_allocated > 0),
    rental_start_date    date NOT NULL,
    rental_end_date      date NOT NULL,
    allocation_status    varchar(20) NOT NULL DEFAULT 'held'
                         CHECK (allocation_status IN ('held', 'reserved', 'released', 'returned')),
    hold_expires_at      timestamptz,
    returned_at          timestamptz,
    created_at           timestamptz NOT NULL DEFAULT now(),
    CHECK (rental_end_date >= rental_start_date),
    CHECK ((allocation_status = 'held' AND hold_expires_at IS NOT NULL) OR allocation_status <> 'held'),
    CHECK (allocation_status <> 'returned' OR returned_at IS NOT NULL),
    UNIQUE (booking_item_id, item_id)
);

-- Protect allocation lineage: direct rentals allocate their selected item;
-- package lines allocate exactly each required component quantity.
CREATE OR REPLACE FUNCTION validate_allocation_lineage()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    line_item_id integer;
    line_package_id integer;
    line_quantity integer;
    line_booking_id integer;
    expected_quantity integer;
    booking_start date;
    booking_end date;
BEGIN
    SELECT bi.item_id, bi.package_id, bi.quantity, bi.booking_id
      INTO line_item_id, line_package_id, line_quantity, line_booking_id
      FROM booking_items bi
     WHERE bi.booking_item_id = NEW.booking_item_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Booking item % does not exist', NEW.booking_item_id;
    END IF;

    SELECT b.event_start_date, b.event_end_date
      INTO booking_start, booking_end
      FROM bookings b
     WHERE b.booking_id = line_booking_id;

    IF NEW.rental_start_date <> booking_start OR NEW.rental_end_date <> booking_end THEN
        RAISE EXCEPTION 'Allocation dates must match the booking event dates';
    END IF;

    IF line_item_id IS NOT NULL THEN
        IF NEW.item_id <> line_item_id OR NEW.quantity_allocated <> line_quantity THEN
            RAISE EXCEPTION 'Direct-item allocation must match the booking line item and quantity';
        END IF;
    ELSE
        SELECT pi.quantity * line_quantity
          INTO expected_quantity
          FROM package_items pi
         WHERE pi.package_id = line_package_id
           AND pi.item_id = NEW.item_id;
        IF expected_quantity IS NULL OR NEW.quantity_allocated <> expected_quantity THEN
            RAISE EXCEPTION 'Allocation must match a package component and its required quantity';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_validate_allocation_lineage
BEFORE INSERT ON booking_item_allocations
FOR EACH ROW EXECUTE FUNCTION validate_allocation_lineage();

