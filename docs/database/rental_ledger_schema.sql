-- Rental Ledger Version 1: PostgreSQL + pgvector
-- Scope: multi-vendor rental inventory, decoration packages, bookings,
-- transaction-safe allocations, payments, cancellations, returns and semantic search.
-- IMPORTANT COURSE ASSUMPTION:
-- This design treats PostgreSQL (relational paradigm) + pgvector (vector-search
-- paradigm) as the required minimum of two paradigms. pgvector is a PostgreSQL
-- extension, not a separate database product. Confirm that the instructor accepts it.
-- If a separate NoSQL product is mandatory, this architecture must be revised.
--
-- Suggested embedding model: sentence-transformers/all-MiniLM-L6-v2 (384 dimensions).
-- If a different model is selected, change vector(384) to that model's output dimension.
-- Install the pgvector extension package on the server before running this script.

